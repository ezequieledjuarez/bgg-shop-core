def test_invoice_view_enforces_owner_and_missing_records(migrated):
    from django.test import RequestFactory
    from django.urls import Resolver404, resolve

    seed_cart(migrated, 1, Decimal("25.00"))
    result = checkout(1, uuid.uuid4())
    assert result["userErrors"] == []
    order_id = result["order"]["id"]
    request = RequestFactory().get(f"/invoices/{order_id}/")
    request.user = SimpleNamespace(pk=1)
    match = resolve(request.path)
    response = match.func(request, **match.kwargs)
    assert response.status_code == 200
    assert response["Content-Type"] == "application/pdf"
    assert response.content.startswith(b"%PDF-")

    request.user = SimpleNamespace(pk=2)
    assert match.func(request, **match.kwargs).status_code == 404
    request.user = SimpleNamespace(pk=1)
    assert orders.invoice_pdf(request, uuid.uuid4()).status_code == 404
    with migrated.cursor() as cursor:
        cursor.execute("DELETE FROM invoice WHERE order_id = %s", [order_id])
    assert match.func(request, **match.kwargs).status_code == 404
    with pytest.raises(Resolver404):
        resolve("/invoices/not-a-uuid/")


