def test_rejection_cleanup_command_is_explicit_bounded_and_preserves_success(migrated):
    from io import StringIO
    from django.core.management import call_command
    from django.core.management.base import CommandError

    expired, fresh, other, success = (uuid.uuid4() for _ in range(4))
    assert redeem(1, "f" * 64, expired)["userErrors"]
    assert redeem(1, "f" * 64, fresh)["userErrors"]
    assert redeem(2, "f" * 64, other)["userErrors"]
    code = issue(migrated)
    assert redeem(1, code, success)["userErrors"] == []
    with migrated.cursor() as cursor:
        cursor.execute("UPDATE credit_idempotency SET created_at = CURRENT_TIMESTAMP - INTERVAL '31 days' "
                       "WHERE idempotency_key IN (%s, %s, %s)", [str(expired), str(other), str(success)])
    output = StringIO()
    call_command("prune_credit_rejections", stdout=output)
    assert scalar(migrated, "SELECT count(*) FROM credit_idempotency") == 4
    with pytest.raises(CommandError):
        call_command("prune_credit_rejections", apply=True, batch_size=0, stdout=output)
    assert scalar(migrated, "SELECT count(*) FROM credit_idempotency") == 4
    call_command("prune_credit_rejections", apply=True, batch_size=1, max_batches=1, stdout=output)
    assert scalar(migrated, "SELECT count(*) FROM credit_idempotency") == 3
    call_command("prune_credit_rejections", apply=True, stdout=output)
    assert scalar(migrated, "SELECT count(*) FROM credit_idempotency") == 2
    for key in (fresh, success):
        assert scalar(migrated, "SELECT count(*) FROM credit_idempotency WHERE idempotency_key = %s", [str(key)]) == 1
    assert redeem(1, code, success)["userErrors"] == []


