def execute(query, user_id, data):
    result = schema.execute(query, variable_values={"input": data},
                            context_value=SimpleNamespace(user=SimpleNamespace(pk=user_id)))
    assert result.errors is None
    return next(iter(result.data.values()))


def concurrent(*operations):
    barrier = threading.Barrier(len(operations), timeout=10)

    def run(operation):
        try:
            with transaction.atomic():
                with connections["default"].cursor() as cursor:
                    cursor.execute("SELECT pg_backend_pid()")
                    backend = cursor.fetchone()[0]
                barrier.wait()
                return backend, operation()
        finally:
            connections.close_all()

    with ThreadPoolExecutor(max_workers=len(operations)) as pool:
        futures = [pool.submit(run, operation) for operation in operations]
        results = [future.result(timeout=20) for future in futures]
    assert len({backend for backend, _ in results}) == len(operations)
    return [result for _, result in results]


def scalar(db, query, params=()):
    with db.cursor() as cursor:
        cursor.execute(query, params)
        return cursor.fetchone()[0]


def issue(db):
    code = secrets.token_hex(32)
    with db.cursor() as cursor:
        cursor.execute("INSERT INTO gift_card (id, code_hash, amount, currency) VALUES (%s, %s, 25, 'ARS')",
                       [str(uuid.uuid4()), hashlib.sha256(code.encode()).digest()])
    return code


def redeem(user_id, code, key):
    return execute(REDEEM, user_id, {"code": code, "idempotencyKey": str(key)})


def checkout(user_id, key, **changes):
    return execute(CHECKOUT, user_id, {"shippingMode": "PICKUP", "idempotencyKey": str(key), **changes})


def seed_cart(db, user_id, balance, quantity=1):
    with db.cursor() as cursor:
        cursor.execute("INSERT INTO credit_account (user_id, balance) VALUES (%s, %s)", [user_id, balance])
        cart = str(uuid.uuid4())
        cursor.execute("INSERT INTO shopping_cart (cart_id, user_id) VALUES (%s, %s)", [cart, user_id])
        cursor.execute("INSERT INTO shopping_cart_line VALUES (%s, 7, %s)", [cart, quantity])


@pytest.mark.parametrize("operation", ["REDEEM", "CHECKOUT"])
def test_expired_rejection_can_be_reused_but_success_never_expires(migrated, operation):
    key = uuid.uuid4()
    if operation == "REDEEM":
        code = issue(migrated)
        failed = redeem(1, "f" * 64, key)
        assert failed["userErrors"][0]["code"] == "INVALID_GIFT_CARD"
        assert redeem(1, code, key)["userErrors"][0]["code"] == "IDEMPOTENCY_CONFLICT"
    else:
        seed_cart(migrated, 1, 0)
        failed = checkout(1, key)
        assert failed["userErrors"][0]["code"] == "INSUFFICIENT_CREDIT"
        with migrated.cursor() as cursor:
            cursor.execute("UPDATE credit_account SET balance = 25 WHERE user_id = 1")
        assert checkout(1, key) == failed
    with migrated.cursor() as cursor:
        cursor.execute(
            "UPDATE credit_idempotency SET created_at = CURRENT_TIMESTAMP - INTERVAL '31 days' "
            "WHERE user_id = 1 AND operation = %s AND idempotency_key = %s", [operation, str(key)],
        )
    result = redeem(1, code, key) if operation == "REDEEM" else checkout(1, key)
    assert result["userErrors"] == []
    with migrated.cursor() as cursor:
        cursor.execute(
            "UPDATE credit_idempotency SET created_at = CURRENT_TIMESTAMP - INTERVAL '31 days' "
            "WHERE user_id = 1 AND operation = %s AND idempotency_key = %s", [operation, str(key)],
        )
    replay = redeem(1, code, key) if operation == "REDEEM" else checkout(1, key)
    assert replay == result
    changed = redeem(1, "e" * 64, key) if operation == "REDEEM" else checkout(1, key, address={"city": "Other"})
    assert changed["userErrors"][0]["code"] == "IDEMPOTENCY_CONFLICT"
    assert scalar(migrated, "SELECT count(*) FROM credit_idempotency WHERE user_id = 1 AND operation = %s", [operation]) == 1
    assert scalar(migrated, "SELECT count(*) FROM credit_transaction WHERE user_id = 1") == 1


