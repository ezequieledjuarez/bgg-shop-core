def test_rejection_cleanup_command_is_explicit_bounded_and_preserves_success(migrated):
    from io import StringIO
    from django.core.management import call_command
    from django.core.management.base import CommandError

    expired, fresh, other, success = (uuid.uuid4() for _ in range(4))
    assert redeem(1, "f" * 64, expired)["userErrors"]
    assert redeem(1, "f" * 64, fresh)["userErrors"]
    assert redeem(2, "f" * 64, other)["userErrors"]
    code = issue(migrated)
    assert redeem(1, code, success)["userErrors"] == []
    with migrated.cursor() as cursor:
        cursor.execute("UPDATE credit_idempotency SET created_at = CURRENT_TIMESTAMP - INTERVAL '31 days' "
                       "WHERE idempotency_key IN (%s, %s, %s)", [str(expired), str(other), str(success)])
    output = StringIO()
    call_command("prune_credit_rejections", stdout=output)
    assert scalar(migrated, "SELECT count(*) FROM credit_idempotency") == 4
    with pytest.raises(CommandError):
        call_command("prune_credit_rejections", apply=True, batch_size=0, stdout=output)
    assert scalar(migrated, "SELECT count(*) FROM credit_idempotency") == 4
    call_command("prune_credit_rejections", apply=True, batch_size=1, max_batches=1, stdout=output)
    assert scalar(migrated, "SELECT count(*) FROM credit_idempotency") == 3
    call_command("prune_credit_rejections", apply=True, stdout=output)
    assert scalar(migrated, "SELECT count(*) FROM credit_idempotency") == 2
    for key in (fresh, success):
        assert scalar(migrated, "SELECT count(*) FROM credit_idempotency WHERE idempotency_key = %s", [str(key)]) == 1
    assert redeem(1, code, success)["userErrors"] == []


def test_rejection_expiry_boundary_is_exactly_30_days(migrated):
    from datetime import timedelta
    from django.utils import timezone

    now = timezone.now()
    key = uuid.uuid4()
    assert redeem(1, "f" * 64, key)["userErrors"]
    code = issue(migrated)
    with migrated.cursor() as cursor:
        cursor.execute("UPDATE credit_idempotency SET created_at = %s WHERE idempotency_key = %s",
                       [now - timedelta(days=30) + timedelta(microseconds=1), str(key)])
    with patch("saleor.graphql.credit.timezone.now", return_value=now):
        assert redeem(1, code, key)["userErrors"][0]["code"] == "IDEMPOTENCY_CONFLICT"
        with migrated.cursor() as cursor:
            cursor.execute("UPDATE credit_idempotency SET created_at = %s WHERE idempotency_key = %s",
                           [now - timedelta(days=30), str(key)])
        assert redeem(1, code, key)["userErrors"] == []


def test_rejection_cleanup_skips_locked_accounts(migrated):
    from io import StringIO
    from django.core.management import call_command

    first, second = uuid.uuid4(), uuid.uuid4()
    assert redeem(1, "f" * 64, first)["userErrors"]
    assert redeem(2, "f" * 64, second)["userErrors"]
    with migrated.cursor() as cursor:
        cursor.execute("UPDATE credit_idempotency SET created_at = CURRENT_TIMESTAMP - INTERVAL '31 days'")
    entered, release = threading.Event(), threading.Event()

    def lock_first_account():
        try:
            with transaction.atomic(), connections["default"].cursor() as cursor:
                cursor.execute("SELECT user_id FROM credit_account WHERE user_id = 1 FOR UPDATE")
                entered.set()
                assert release.wait(5)
        finally:
            connections.close_all()

    with ThreadPoolExecutor(max_workers=1) as pool:
        future = pool.submit(lock_first_account)
        try:
            assert entered.wait(5)
            call_command("prune_credit_rejections", apply=True, stdout=StringIO())
            assert scalar(migrated, "SELECT count(*) FROM credit_idempotency WHERE idempotency_key = %s", [str(first)]) == 1
            assert scalar(migrated, "SELECT count(*) FROM credit_idempotency WHERE idempotency_key = %s", [str(second)]) == 0
        finally:
            release.set()
        future.result(timeout=10)
    call_command("prune_credit_rejections", apply=True, stdout=StringIO())
    assert scalar(migrated, "SELECT count(*) FROM credit_idempotency") == 0


