def test_migration_executor_applies_and_records_credit_migrations(database):
    from django.db.migrations.exceptions import IrreversibleError
    from django.db.migrations.executor import MigrationExecutor
    from django.db.migrations.recorder import MigrationRecorder

    before = scalar(database, "SELECT id FROM purchase_order")
    with database.cursor() as cursor:
        cursor.execute(GIFT_DDL)
        cursor.execute(
            "INSERT INTO gift_card (id, code_hash, amount, currency) VALUES (%s, %s, 25, 'ARS')",
            [str(uuid.uuid4()), hashlib.sha256(b"synthetic-test-code").digest()],
        )
    recorder = MigrationRecorder(database)
    recorder.record_applied("contenttypes", "0001_initial")
    recorder.record_applied("auth", "0001_initial")
    executor = MigrationExecutor(database)
    target = [("graphql", "0005_credit_payment_review_resolution")]
    executor.migrate(target)
    applied = recorder.applied_migrations()
    assert all(("graphql", name) in applied for name in (
        "0001_credit_accounts", "0002_credit_checkout", "0003_credit_retry_guard", "0004_credit_payment_review", "0005_credit_payment_review_resolution",
    ))
    assert scalar(database, "SELECT id FROM purchase_order") == before
    assert scalar(database, "SELECT count(*) FROM gift_card") == 1
    assert scalar(database, "SELECT quantity FROM product_boardgame WHERE bgg_id = 7") == 5
    assert MigrationExecutor(database).migration_plan(target) == []
    with pytest.raises(IrreversibleError):
        MigrationExecutor(database).migrate([("graphql", "0004_credit_payment_review")])
    assert ("graphql", "0005_credit_payment_review_resolution") in recorder.applied_migrations()
    assert scalar(database, "SELECT count(*) FROM credit_retry_guard") == 0
    assert scalar(database, "SELECT count(*) FROM credit_payment_review") == 0
    assert scalar(database, "SELECT count(*) FROM credit_payment_review_resolution") == 0


