def test_concurrent_reuse_of_expired_rejection_credits_only_once(migrated):
    key = uuid.uuid4()
    assert redeem(1, "f" * 64, key)["userErrors"]
    code = issue(migrated)
    with migrated.cursor() as cursor:
        cursor.execute("UPDATE credit_idempotency SET created_at = CURRENT_TIMESTAMP - INTERVAL '31 days' "
                       "WHERE idempotency_key = %s", [str(key)])
    results = concurrent(lambda: redeem(1, code, key), lambda: redeem(1, code, key))
    assert results[0] == results[1] and results[0]["userErrors"] == []
    assert scalar(migrated, "SELECT count(*) FROM credit_transaction WHERE user_id = 1") == 1
    assert scalar(migrated, "SELECT count(*) FROM credit_idempotency WHERE idempotency_key = %s", [str(key)]) == 1


