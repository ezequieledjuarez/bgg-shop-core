def test_new_payment_waits_for_release_and_creates_new_block(migrated):
    from saleor.graphql import api

    seed_cart(migrated, 1, 25)
    provider_order = seed_rejected(migrated)
    with migrated.cursor() as cursor:
        cursor.execute("UPDATE purchase_order SET mp_preference_id = 'new-preference' WHERE id = %s", [provider_order])
        cursor.execute("INSERT INTO credit_payment_review (order_id, payment_id) VALUES (%s, 'old-payment')", [provider_order])
        cursor.execute("INSERT INTO credit_payment_review_resolution (order_id, payment_id, actor_user_id, action, reason) VALUES (%s, 'old-payment', 1, 'Reviewed', 'Verified')", [provider_order])
    payment = {"status": 200, "response": {
        "external_reference": provider_order, "transaction_amount": 12.50,
        "currency_id": "ARS", "status": "approved",
    }}
    locked, release, confirm_started = threading.Event(), threading.Event(), threading.Event()
    release_pid, confirm_pid = [], []
    lock_account = api._lock_credit_account

    def paused_lock(cursor, user_id):
        lock_account(cursor, user_id)
        locked.set()
        assert release.wait(5)

    def release_worker():
        try:
            with connections["default"].cursor() as cursor:
                cursor.execute("SELECT pg_backend_pid()")
                release_pid.append(cursor.fetchone()[0])
            return release_review(provider_order, "old-payment", SimpleNamespace(pk=1, is_staff=True))
        finally:
            connections.close_all()

    def confirm_worker():
        try:
            with connections["default"].cursor() as cursor:
                cursor.execute("SELECT pg_backend_pid()")
                confirm_pid.append(cursor.fetchone()[0])
            confirm_started.set()
            info = SimpleNamespace(context=SimpleNamespace(user=SimpleNamespace(pk=1)))
            return orders.confirm_payment(info, provider_order, "new-payment")
        finally:
            connections.close_all()

    with patch.object(api, "_lock_credit_account", side_effect=paused_lock), \
            patch.object(orders.payments, "fetch_payment", return_value=confirmed_payment_response(payment, "new-payment")), \
            patch.object(orders.payments, "verified_preference", return_value="old-preference"), \
            ThreadPoolExecutor(max_workers=2) as pool:
        release_future = pool.submit(release_worker)
        try:
            assert locked.wait(5)
            confirm_future = pool.submit(confirm_worker)
            assert confirm_started.wait(5)
            wait = threading.Event()
            for _ in range(100):
                if release_pid[0] in scalar(migrated, "SELECT pg_blocking_pids(%s)", [confirm_pid[0]]):
                    break
                wait.wait(0.02)
            else:
                pytest.fail("Payment confirmation did not wait for the release")
        finally:
            release.set()
        assert release_future.result(timeout=10)["userErrors"] == []
        assert confirm_future.result(timeout=10).user_errors[0].code == "PAYMENT_REQUIRES_REVIEW"
    assert scalar(migrated, "SELECT count(*) FROM credit_payment_review_release WHERE order_id = %s", [provider_order]) == 1
    assert scalar(migrated, "SELECT count(*) FROM credit_payment_review WHERE order_id = %s", [provider_order]) == 2
