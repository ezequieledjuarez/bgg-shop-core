def test_credit_first_blocks_concurrent_retry_and_preserves_other_orders(migrated):
    seed_cart(migrated, 1, 25)
    order_id = seed_rejected(migrated)
    other = seed_rejected(migrated, 2)
    entered, release, retry_started = threading.Event(), threading.Event(), threading.Event()
    credit_pid, retry_pid = [], []
    purchase = credit._checkout_purchase

    def paused_purchase(*args):
        result = purchase(*args)
        entered.set()
        assert release.wait(5)
        return result

    def credit_worker():
        try:
            with connections["default"].cursor() as cursor:
                cursor.execute("SELECT pg_backend_pid()")
                credit_pid.append(cursor.fetchone()[0])
            return checkout(1, uuid.uuid4())
        finally:
            connections.close_all()

    def retry_worker():
        with connections["default"].cursor() as cursor:
            cursor.execute("SELECT pg_backend_pid()")
            retry_pid.append(cursor.fetchone()[0])
        retry_started.set()
        return retry(order_id)

    with patch.object(orders.payments, "configuration_error", return_value=None), \
            patch.object(orders, "_preference", return_value=("simulated", "https://example.invalid")) as preference, \
            patch.object(credit, "_checkout_purchase", side_effect=paused_purchase), \
            ThreadPoolExecutor(max_workers=2) as pool:
        credit_future = pool.submit(credit_worker)
        try:
            assert entered.wait(5)
            retry_future = pool.submit(retry_worker)
            assert retry_started.wait(5)
            wait = threading.Event()
            for _ in range(100):
                if credit_pid[0] in scalar(migrated, "SELECT pg_blocking_pids(%s)", [retry_pid[0]]):
                    break
                wait.wait(0.02)
            else:
                pytest.fail("Retry did not wait for the credit account lock")
        finally:
            release.set()
        assert credit_future.result(timeout=10)["userErrors"] == []
        assert retry_future.result(timeout=10).user_errors[0].code == "ORDER_NOT_PAYABLE"
        preference.assert_not_called()
        assert retry(other, 2).user_errors == []
        later = seed_rejected(migrated)
        assert retry(later).user_errors == []
    assert scalar(migrated, "SELECT count(*) FROM credit_retry_guard") == 1


def test_pending_order_rejected_during_checkout_is_guarded(migrated):
    seed_cart(migrated, 1, 25)
    order_id = seed_rejected(migrated)
    with migrated.cursor() as cursor:
        cursor.execute("UPDATE purchase_order SET status = 'pending_payment' WHERE id = %s", [order_id])
    started, worker_pid = threading.Event(), []

    def credit_worker():
        try:
            with connections["default"].cursor() as cursor:
                cursor.execute("SELECT pg_backend_pid()")
                worker_pid.append(cursor.fetchone()[0])
            started.set()
            return checkout(1, uuid.uuid4())
        finally:
            connections.close_all()

    with ThreadPoolExecutor(max_workers=1) as pool:
        with transaction.atomic(), migrated.cursor() as cursor:
            cursor.execute("SELECT pg_backend_pid()")
            blocker = cursor.fetchone()[0]
            cursor.execute("UPDATE purchase_order SET status = 'rejected' WHERE id = %s", [order_id])
            future = pool.submit(credit_worker)
            assert started.wait(5)
            wait = threading.Event()
            for _ in range(100):
                cursor.execute("SELECT pg_blocking_pids(%s)", [worker_pid[0]])
                if blocker in cursor.fetchone()[0]:
                    break
                wait.wait(0.02)
            else:
                pytest.fail("Credit checkout did not wait for the order lock")
        assert future.result(timeout=10)["userErrors"] == []
    assert scalar(migrated, "SELECT count(*) FROM credit_retry_guard WHERE order_id = %s", [order_id]) == 1


