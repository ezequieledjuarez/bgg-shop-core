def test_pending_provider_order_blocks_concurrent_credit_checkout(migrated):
    seed_cart(migrated, 1, 25)
    started = threading.Event()
    worker_pid = []

    def pay_with_credit():
        try:
            with connections["default"].cursor() as cursor:
                cursor.execute("SELECT pg_backend_pid()")
                worker_pid.append(cursor.fetchone()[0])
            started.set()
            return checkout(1, uuid.uuid4())
        finally:
            connections.close_all()

    with ThreadPoolExecutor(max_workers=1) as pool:
        with transaction.atomic(), migrated.cursor() as cursor:
            cursor.execute("SELECT pg_backend_pid()")
            blocker_pid = cursor.fetchone()[0]
            cursor.execute("SELECT cart_id FROM shopping_cart WHERE user_id = %s FOR UPDATE", [1])
            cursor.execute(
                "INSERT INTO purchase_order (id, user_id, status, total, currency, shipping_mode) "
                "VALUES (%s, %s, %s, %s, %s, %s)",
                [str(uuid.uuid4()), 1, "pending_payment", 12.50, "ARS", "pickup"],
            )
            future = pool.submit(pay_with_credit)
            assert started.wait(timeout=3)
            wait = threading.Event()
            for _ in range(100):
                cursor.execute("SELECT pg_blocking_pids(%s)", [worker_pid[0]])
                if blocker_pid in cursor.fetchone()[0]:
                    break
                wait.wait(0.02)
            else:
                pytest.fail("Credit checkout did not wait for the locked cart")
        result = future.result(timeout=10)

    assert result["userErrors"][0]["code"] == "PENDING_PAYMENT"
    assert scalar(migrated, "SELECT balance FROM credit_account WHERE user_id = 1") == Decimal("25.00")
    assert scalar(migrated, "SELECT quantity FROM product_boardgame WHERE bgg_id = 7") == 5
    assert scalar(migrated, "SELECT quantity FROM shopping_cart_line") == 1
    assert scalar(migrated, "SELECT count(*) FROM purchase_order") == 2
    assert scalar(migrated, "SELECT count(*) FROM invoice") == 0
    assert scalar(migrated, "SELECT count(*) FROM credit_payment") == 0


